export const presentationLevelPacks: LevelPack[] = presentationSections.map((section) => ({
  id: section.id,
  order: section.order,
  titleKey: section.title,
  access: "free",
  status: "published",
  levels: section.patterns.map((pattern, index) => levelFromPattern(section.id, section.title, pattern, index))
}));

function levelFromPattern(packId: string, packTitle: string, pattern: LevelPattern, index: number): Level {
  const rows = pattern.length;
  const cols = pattern[0]?.length ?? 0;
  const holes: CellCoord[] = [];
  const requiredSeeds: CellCoord[] = [];
  const blockedSeeds: CellCoord[] = [];

  pattern.forEach((line, row) => {
    if (line.length !== cols) throw new Error(`Invalid level pattern width for ${packId}-${index + 1}`);

    [...line].forEach((cell, col) => {
      if (cell === ".") holes.push([row, col]);
      if (cell === "A") requiredSeeds.push([row, col]);
      if (cell === "R") blockedSeeds.push([row, col]);
    });
  });

  const three = Math.ceil(boardPerimeter(pattern) / 4);
  const order = 23 + presentationSections
    .filter((section) => section.order < presentationSections.find((section) => section.id === packId)!.order)
    .reduce((total, section) => total + section.patterns.length, 0) + index;

  return {
    id: `${packId}-${String(index + 1).padStart(2, "0")}`,
    packId,
    order,
    titleKey: `${packTitle} ${String(index + 1).padStart(2, "0")}`,
    rows,
    cols,
    maxSeeds: three + 2,
    free: true,
    stars: { three, two: three + 1, one: three + 2 },
    holes,
    requiredSeeds,
    blockedSeeds
  };
}

function boardPerimeter(pattern: LevelPattern): number {
  const isCell = (row: number, col: number): boolean => (
    row >= 0 && row < pattern.length && col >= 0 && col < pattern[row].length && pattern[row][col] !== "."
  );

  let perimeter = 0;
  pattern.forEach((line, row) => {
    [...line].forEach((cell, col) => {
      if (cell === ".") return;
      if (!isCell(row - 1, col)) perimeter += 1;
      if (!isCell(row + 1, col)) perimeter += 1;
      if (!isCell(row, col - 1)) perimeter += 1;
      if (!isCell(row, col + 1)) perimeter += 1;
    });
  });
  return perimeter;
}
